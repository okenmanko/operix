function normalizeLang(value: string | null): Lang {
  if (value === "ru" || value === "en" || value === "uz") return value;
  return "uz";
}

const I18nContext = createContext<I18nValue>({
  lang: "uz",
  setLang: () => {},
  t: (key: string, fallback?: string) => fallback || key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("uz");

  useEffect(() => {
    setLangState(normalizeLang(localStorage.getItem("qanot_lang") || localStorage.getItem("operix_lang")));
  }, []);

  function setLang(next: Lang) {
    setLangState(next);
    if (typeof window !== "undefined") {
      localStorage.setItem("qanot_lang", next);
      localStorage.setItem("operix_lang", next);
    }
  }

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: (key: string, fallback?: string) => dictionary[lang]?.[key] || fallback || key,
  }), [lang]);

  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() { return useContext(I18nContext); }
export function t(key: string, fallback?: string) { return dictionary.uz[key] || fallback || key; }
